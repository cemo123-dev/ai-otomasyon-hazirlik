import { chromium } from 'playwright-core';
import { mkdirSync } from 'node:fs';
const BASE = process.env.BASE_URL ?? 'http://localhost:8084';
const OUT = 'e2e/shots/'; mkdirSync(OUT, { recursive: true });
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errs = []; p.on('pageerror', e => errs.push('PAGEERROR ' + e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text().slice(0, 200)));
await p.goto(`${BASE}/match/9004`, { timeout: 180000 });
await p.getByText('AI Taktik').click();
await p.getByRole('button', { name: /Pro/ }).first().click();
await p.getByText('Aboneliği Başlat (Simülasyon)').click();
await p.waitForTimeout(1500);
if (await p.getByText('Aboneliği Başlat (Simülasyon)').count()) await p.goBack();
await p.getByText('TAKTİK ASİSTANA SOR', { exact: true }).first().waitFor({ timeout: 30000 }); console.log('sohbet kutusu: OK');
// Tasarım tur 2 R-4: sayaç kalan hakkı açık yazar ("Kalan: 3/3"), hak bitince "Hak doldu"
console.log('sayaç:', await p.getByText(/^Kalan: \d\/3$/).first().textContent());
await p.getByText('Maçın kırılma anı neydi?').click();
await p.getByText('Maç verisine bakılıyor…').waitFor({ timeout: 5000 }); console.log('bekleniyor durumu: OK');
await p.getByText('Maç verisine bakılıyor…').waitFor({ state: 'detached', timeout: 10000 });
const after1 = await p.getByText(/^Kalan: \d\/3$/).first().textContent();
if (after1 !== 'Kalan: 2/3') throw new Error(`1 sorudan sonra sayaç: ${after1}`);
console.log('yanıt 1: OK, sayaç:', after1);
await p.getByPlaceholder('Örn: Neden 70. dakikada forvet çıktı?').fill('Neden 70. dakikada forvet çıktı?');
await p.getByLabel('Soruyu gönder').click();
await p.getByText('Maç verisine bakılıyor…').waitFor({ state: 'detached', timeout: 10000 });
await p.getByText('Teknik direktör hamleleri işe yaradı mı?').click();
await p.getByText('Maç verisine bakılıyor…').waitFor({ state: 'detached', timeout: 10000 });
await p.getByText('soru hakkın doldu', { exact: false }).waitFor({ timeout: 5000 });
await p.getByText('Hak doldu', { exact: true }).waitFor({ timeout: 5000 });
if (await p.getByText(/^Kalan: /).count()) throw new Error('hak bitince "Kalan:" sayacı hâlâ görünüyor');
console.log('3 soru sonrası limit: OK, sayaç: Hak doldu');
await p.getByText('TAKTİK ASİSTANA SOR', { exact: true }).first().scrollIntoViewIfNeeded();
await p.waitForTimeout(300);
await p.screenshot({ path: OUT + 'c1-sohbet.png' });
console.log('hatalar:', errs.length ? errs : 'yok'); await b.close(); if (errs.length) process.exit(1);
