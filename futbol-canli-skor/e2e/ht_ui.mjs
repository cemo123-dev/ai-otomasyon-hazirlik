import { chromium } from 'playwright-core';
import { mkdirSync } from 'node:fs';
const BASE = process.env.BASE_URL ?? 'http://localhost:8084';
const OUT = 'e2e/shots/'; mkdirSync(OUT, { recursive: true });
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errs = []; p.on('pageerror', e => errs.push('PAGEERROR ' + e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text().slice(0, 200)));
await p.goto(`${BASE}`, { timeout: 180000 });
await p.getByText('Anadolu Gücü').first().waitFor({ timeout: 150000 });
await p.getByLabel(/maçını takip et$/).first().click();
await p.getByLabel(/maçının takibini bırak$/).first().waitFor({ timeout: 5000 }); console.log('listede zil: OK');
await p.getByText('Anadolu Gücü').first().click();
await p.getByText('🔔 Takip ediliyor', { exact: false }).waitFor({ timeout: 10000 }); console.log('maç ekranında takip: OK');
await p.getByText('AI Taktik').click();
await p.getByText('Devre arası AI raporu Pro üyelere özel').waitFor({ timeout: 60000 }); console.log('HT kilitli durum: OK');
await p.waitForTimeout(3500);
await p.screenshot({ path: OUT + 'h1-kilit.png' });
await p.getByText("Pro'ya Geçerek Raporu Aç").click();
await p.getByText('Aboneliği Başlat (Simülasyon)').click();
await p.getByText('İKİNCİ YARIDA NE OLMALI?', { exact: true }).waitFor({ timeout: 20000 }); console.log('rapor: OK');
await p.waitForTimeout(400);
await p.screenshot({ path: OUT + 'h2-rapor.png', fullPage: true });
await p.goBack();
await p.getByText('✦ Devre Arası AI Hazır').first().waitFor({ timeout: 10000 }); console.log('listede rozet: OK');
console.log('hatalar:', errs.length ? errs : 'yok'); await b.close(); if (errs.length) process.exit(1);
